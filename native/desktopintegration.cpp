bool DesktopIntegration::configure(bool enabled, const QString &executable, QString *error)
{
    bool ok = true;
#ifdef Q_OS_MACOS
    const auto root = qEnvironmentVariable("ATHANOR_INTEGRATION_DIR", QDir::homePath() + "/Library/Services");
    for (const auto &group : groups())
        for (int i = 0; i < group.targets.size(); i++)
        {
            const auto bundle = root + "/Athanor - " + group.name + " - " + group.labels[i] + ".workflow";
            const auto path = bundle + "/Contents/document.wflow";
            ok = ownedWrite(path, workflow(script(executable, group, group.targets[i]), group.inputType).toUtf8(), enabled) && ok;
            const auto uti = group.name == "GIF" ? "com.compuserve.gif"
                             : group.inputType == "pdf" ? "com.adobe.pdf" : "public." + group.inputType;
            const auto info = QString::fromUtf8(R"XML(<?xml version="1.0" encoding="UTF-8"?>
<plist version="1.0"><dict><!-- Generated by Athanor -->
<key>NSServices</key><array><dict>
<key>NSMenuItem</key><dict><key>default</key><string>%1</string></dict>
<key>NSMessage</key><string>runWorkflowAsService</string>
<key>NSRequiredContext</key><dict><key>NSApplicationIdentifier</key><string>com.apple.finder</string></dict>
<key>NSSendFileTypes</key><array><string>%2</string></array>
</dict></array></dict></plist>)XML").arg(("Athanor - " + group.name + " - " + group.labels[i]).toHtmlEscaped(), uti);
            ok = ownedWrite(bundle + "/Contents/Info.plist", info.toUtf8(), enabled) && ok;
            if (!enabled && noLinks(bundle))
            {
                QDir().rmdir(bundle + "/Contents");
                QDir().rmdir(bundle);
            }
        }
#elif defined(Q_OS_LINUX)
    const auto root = qEnvironmentVariable("ATHANOR_INTEGRATION_DIR", QStandardPaths::writableLocation(QStandardPaths::GenericDataLocation));
    for (const auto &group : groups())
        for (int i = 0; i < group.targets.size(); i++)
        {
            const auto relative = "/Athanor/" + group.name + " - " + group.labels[i];
            const auto command = script(executable, group, group.targets[i]).toUtf8();
            for (const auto &manager : {QString("nautilus"), QString("nemo")})
                ok = ownedWrite(root + '/' + manager + "/scripts" + relative, command, enabled, true) && ok;
            const auto launcher = root + "/athanor/actions/" + group.name + '-' + group.targets[i];
            ok = ownedWrite(launcher, command, enabled, true) && ok;
            const auto service = "[Desktop Entry]\n# Generated by Athanor\nType=Service\nMimeType=" + group.mime +
                                 "\nActions=convert;\nX-KDE-Submenu=Convert using Athanor\n[Desktop Action convert]\nName=" +
                                 group.labels[i] + "\nExec=" + desktopQuote(launcher) + " %F\n";
            ok = ownedWrite(root + "/kio/servicemenus/athanor-" + group.name + '-' + group.targets[i] + ".desktop", service.toUtf8(), enabled, true) && ok;
        }
#else
    Q_UNUSED(enabled);
    Q_UNUSED(executable);
#endif
    if (!ok && error)
        *error = "Could not save file manager actions. Check permissions and existing Athanor action files.";
    return ok;
}
