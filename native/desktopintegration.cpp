const QByteArray marker = "Generated by Athanor";
struct Group
{
    QString name, inputType, mime;
    QStringList extensions, targets, labels;
};
QList<Group> groups()
{
    QList<Group> result{{"Images", "image", "image/*;", Conversion::imageExtensions(),
             {"avif", "webp", "heic", "heif", "jpg", "png", "ico", "images-pdf"},
             {"Convert to AVIF", "Convert to WebP", "Convert to HEIC", "Convert to HEIF", "Convert to JPG",
              "Convert to PNG", "Convert to ICO", "Create PDF"}},
            {"Video", "movie", "video/*;image/gif;", Conversion::videoExtensions(),
             {"webm", "mkv", "av1", "mp4", "gif", "opus", "mp3", "wav"},
             {"Convert to WebM", "Convert to MKV", "Convert to .av1 (video only)", "Convert to MP4",
              "Convert to GIF", "Extract Opus audio", "Extract MP3 audio", "Extract WAV audio"}},
            {"Audio", "audio", "audio/*;", Conversion::audioExtensions(), {"opus", "mp3", "wav"},
             {"Convert to Opus", "Convert to MP3", "Convert to WAV"}},
            {"PDF", "pdf", "application/pdf;", {"pdf"}, {"pdf", "pdf-jpg"},
             {"Compress PDF", "Export JPG pages"}}};
#ifdef Q_OS_MACOS
    // GIF is an image UTI in Finder, but the existing converter treats it as
    // video. Give it the same video targets without hiding those actions.
    const auto video = result[1];
    result.append({"GIF", "image", "image/gif;", {"gif"}, video.targets, video.labels});
#endif
    return result;
}
bool noLinks(const QString &path)
{
    QFileInfo info(path);
    while (true)
    {
        if (info.isSymLink())
            return false;
        auto parent = info.absolutePath();
        if (parent == info.absoluteFilePath())
            return true;
        info.setFile(parent);
    }
}
bool ownedWrite(const QString &path, const QByteArray &bytes, bool enabled, bool executable = false)
{
    if (!noLinks(path))
        return false;
    QFile existing(path);
    if (existing.exists())
    {
        if (!existing.open(QIODevice::ReadOnly) || !existing.readAll().contains(marker))
            return false;
        existing.close();
        if (!enabled)
            return existing.remove();
    }
    if (!enabled)
        return true;
    if (!QDir().mkpath(QFileInfo(path).absolutePath()))
        return false;
    QSaveFile output(path);
    if (!output.open(QIODevice::WriteOnly) || output.write(bytes) != bytes.size() || !output.commit())
        return false;
    return !executable || QFile::setPermissions(path, QFile::ReadOwner | QFile::WriteOwner | QFile::ExeOwner);
}
QString shellQuote(QString value)
{
    value.replace("'", "'\\''");
    return "'" + value + "'";
}
QString desktopQuote(QString value)
{
    value.replace('\\', "\\\\\\\\");
    value.replace('"', "\\\"");
    value.replace('`', "\\`");
    value.replace('$', "\\$");
    value.replace('%', "%%");
    return '"' + value + '"';
}
QString script(const QString &executable, const Group &group, const QString &target)
{
    QStringList patterns;
    for (const auto &ext : group.extensions)
        patterns << "*." + ext;
    return "#!/bin/bash\n# Generated by Athanor\n"
           "if [ \"$#\" -eq 0 ]; then\n"
           "  files=${NAUTILUS_SCRIPT_SELECTED_FILE_PATHS:-${NEMO_SCRIPT_SELECTED_FILE_PATHS:-}}\n"
           "  while IFS= read -r file; do [ -z \"$file\" ] || set -- \"$@\" \"$file\"; done <<< \"$files\"\n"
           "fi\nselected=()\nfor file in \"$@\"; do\n"
           "  lower=$(printf '%s' \"$file\" | tr '[:upper:]' '[:lower:]')\n"
           "  case \"$lower\" in " + patterns.join('|') + ") selected+=(\"$file\");; esac\n"
           "done\n[ \"${#selected[@]}\" -gt 0 ] || exit 0\nexec " + shellQuote(executable) +
           " --quick --target " + shellQuote(target) + " -- \"${selected[@]}\"\n";
}
